"""
D4 Sobol sensitivity sweep — one SLURM array task per Saltelli sample.

Called by slurm/submit_sobol.sh:
    python sensitivity/run_sobol_sweep.py \\
        --sample-id  $SLURM_ARRAY_TASK_ID \\
        --samples-csv  results/sobol/sobol_samples.csv \\
        --syn-flows-dir  results/sobol/synthetic_flows \\
        --outdir  results/sobol/task_outputs

Each task runs SOBOL_ENSEMBLE_SUBSET synthetic realizations with one set of
sensitivity parameter values, writes per-party RRV metrics to
    {outdir}/task_{sample_id:05d}.csv

Prerequisites
-------------
1. python sensitivity/sobol_design.py        # generates sobol_samples.csv
2. python sensitivity/gen_synthetic_flows.py # generates 50 Kirsch-Nowak realizations
3. Baseline run complete (submit_baseline.sh finished)

Design notes
------------
* Synthetic DRB flow realizations are generated by gen_synthetic_flows.py using
  Kirsch-Nowak (synhydro 0.0.2), calibrated on pub_nhmv10_BC_withObsScaled
  catchment inflows (1946–2005).  Each realization covers 79 years relabelled
  as 1945-01-01 → 2023-12-31.  Stored as realization_{r:03d}.parquet.
* Sensitivity parameters are injected into the Pywr-DRB model JSON before
  each run via run_model.run_single(sensitivity_params=...).
* LB drought threshold overrides (alpha_betz_warning, alpha_bm_warning,
  tau_recovery) patch LowerBasinDroughtLevel kwargs via model_dict
  (see ffmp.py LowerBasinDroughtLevel.__init__ — added 2026-05-31).
* q_nj_warning and ierq_max_bg injection is pending model_dict key
  confirmation — both currently emit a UserWarning and use model defaults.
* m_lb uses the existing lb_cap_multiplier mechanism; non-1.0 values
  raise NotImplementedError until that path is wired.
* predicted_inflows_mgd.csv is cached per synthetic realization (not per
  Sobol sample) — it depends only on streamflow, not policy parameters.

References
----------
Saltelli, A. et al. (2010). Variance based sensitivity analysis of model
  output. Design and estimator for the total sensitivity index.
  Computer Physics Communications, 181(2), 259–270.
Kirsch, B.R. et al. (2013). Developing Portfolios of Climate Change Adaptation
  Strategies. J. Water Resources Planning & Management, 139(3), 321–333.
"""

from __future__ import annotations

import argparse
import logging
import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
from concurrent.futures import ProcessPoolExecutor, as_completed

# ---------------------------------------------------------------------------
# Path setup — allow running from repo root or the file's own directory
# ---------------------------------------------------------------------------
_THIS_FILE = Path(__file__).resolve()
_REPO_ROOT = _THIS_FILE.parents[2]          # dissertation/
_SHARED    = _REPO_ROOT / "shared"
_LIB_SENS  = _THIS_FILE.parent.parent / "lib" / "sensitivity"
for _p in [str(_SHARED), str(_REPO_ROOT), str(_LIB_SENS)]:
    if _p not in sys.path:
        sys.path.insert(0, _p)

# Import shared utilities
from pywrdrb_utils.run_model import run_single
from D4_distributed_risk.lib.rrv_metrics.metrics import compute_all_party_rrv
from D4_distributed_risk.experiments.run_d4_baseline import LB_CAPACITY_MG
from config import SOBOL_ENSEMBLE_SUBSET

logger = logging.getLogger(__name__)


def _configure_worker_logging(level: int = logging.WARNING) -> None:
    """Suppress per-component Pywr DEBUG spam in forked worker processes."""
    for name in ("", "pywr", "pywrdrb", "matplotlib"):
        logging.getLogger(name).setLevel(level)


# ---------------------------------------------------------------------------
# Core task runner
# ---------------------------------------------------------------------------

def load_synthetic_realization(syn_flows_dir: Path, realization_id: int) -> pd.DataFrame:
    """
    Load one pre-generated Kirsch-Nowak synthetic realization from parquet.

    Parameters
    ----------
    syn_flows_dir : Path
        Directory containing realization_{r:03d}.parquet files
        (generated by gen_synthetic_flows.py).
    realization_id : int
        Zero-based realization index (0 – SOBOL_ENSEMBLE_SUBSET-1).

    Returns
    -------
    pd.DataFrame
        DatetimeIndex (daily, 1945-01-01 – 2023-12-31), 31 columns (MGD).
        Ready to pass to run_single(flow_df=...).
    """
    parquet_path = syn_flows_dir / f"realization_{realization_id:03d}.parquet"
    if not parquet_path.exists():
        raise FileNotFoundError(
            f"Synthetic realization not found: {parquet_path}\n"
            "Run gen_synthetic_flows.py first."
        )
    df = pd.read_parquet(parquet_path)
    df.index.name = "datetime"
    return df


def _run_one_realization(
    r: int,
    sample_id: int,
    sample_params: dict,
    syn_flows_dir: Path,
) -> dict:
    """Run one Sobol sample × one synthetic realization. Called by worker processes."""
    import warnings as _warnings

    _configure_worker_logging()
    try:
        flow_df = load_synthetic_realization(syn_flows_dir, r)
        inflow_type = f"syn_r{r:03d}"
        predicted_inflows_cache = syn_flows_dir / "predicted_inflows_cache"

        with _warnings.catch_warnings():
            _warnings.filterwarnings("once", message=".*sensitivity injection not yet implemented.*")
            outputs = run_single(
                flow_df=flow_df,
                inflow_type=inflow_type,
                tfo_override=None,
                lb_cap_multiplier=1.0,
                sensitivity_params=sample_params,
                predicted_inflows_cache=predicted_inflows_cache,
                cleanup=True,
            )

        rrv = compute_all_party_rrv(
            outputs,
            lb_capacity_mg=LB_CAPACITY_MG,
            alpha_betz=sample_params.get("alpha_betz_warning"),
            alpha_bm=sample_params.get("alpha_bm_warning"),
            erq_cap_mg=sample_params.get("erq_cap_mg"),  # None in sweep 1; active in sweep 2
        )
        row: dict = {"sample_id": sample_id, "realization_id": r, "status": "ok"}
        row.update(sample_params)
        row.update(rrv)
        return row

    except Exception as exc:
        row = {
            "sample_id": sample_id,
            "realization_id": r,
            "status": f"error: {type(exc).__name__}: {exc}",
        }
        row.update(sample_params)
        return row


def run_one_sobol_task(
    sample_id: int,
    sample_params: dict,
    syn_flows_dir: Path,
    n_realizations: int,
    outdir: Path,
    n_workers: int = 1,
) -> pd.DataFrame:
    """
    Run all synthetic realizations for one Sobol sample row.

    Parameters
    ----------
    sample_id : int
        Row index in sobol_samples.csv (= SLURM_ARRAY_TASK_ID).
    sample_params : dict
        Parameter values from one row of sobol_samples.csv.
    syn_flows_dir : Path
        Directory of pre-generated Kirsch-Nowak parquet files.
    n_realizations : int
        Number of synthetic realizations to run (from SOBOL_ENSEMBLE_SUBSET).
    outdir : Path
        Output directory.  Results written to {outdir}/task_{sample_id:05d}.csv.
    n_workers : int
        Number of parallel worker processes for realizations (default: 1).
        Set to SOBOL_ENSEMBLE_SUBSET or SLURM_CPUS_PER_TASK for full parallelism.

    Returns
    -------
    pd.DataFrame  — one row per realization; columns = sample params + RRV metrics + metadata.
    """
    outdir.mkdir(parents=True, exist_ok=True)
    out_path = outdir / f"task_{sample_id:05d}.csv"

    # Skip only fully complete tasks (partial CSVs from failed runs are redone)
    if out_path.exists():
        try:
            existing = pd.read_csv(out_path)
            n_ok = int((existing["status"] == "ok").sum()) if "status" in existing.columns else 0
            if n_ok >= n_realizations:
                logger.info(f"Output already complete: {out_path} — skipping")
                return existing
            logger.warning(
                f"Incomplete output ({n_ok}/{n_realizations} OK): {out_path} — re-running"
            )
        except Exception as exc:
            logger.warning(f"Unreadable output {out_path} ({exc}) — re-running")

    rows = []
    if n_workers <= 1:
        for r in range(n_realizations):
            logger.debug(f"  Sample {sample_id:5d} | realization {r:03d} ({r+1}/{n_realizations})")
            row = _run_one_realization(r, sample_id, sample_params, syn_flows_dir)
            if row["status"] != "ok":
                logger.error(f"Sample {sample_id} realization {r} FAILED: {row['status']}")
            rows.append(row)
    else:
        with ProcessPoolExecutor(max_workers=n_workers) as pool:
            futures = {
                pool.submit(_run_one_realization, r, sample_id, sample_params, syn_flows_dir): r
                for r in range(n_realizations)
            }
            for fut in as_completed(futures):
                row = fut.result()
                r = futures[fut]
                if row["status"] != "ok":
                    logger.error(f"Sample {sample_id} realization {r} FAILED: {row['status']}")
                else:
                    logger.debug(f"  Sample {sample_id:5d} | realization {r:03d} done")
                rows.append(row)

    df = pd.DataFrame(rows).sort_values("realization_id").reset_index(drop=True)
    df.to_csv(out_path, index=False)
    n_ok  = (df["status"] == "ok").sum()
    n_err = (df["status"] != "ok").sum()
    logger.info(
        f"Sample {sample_id:5d}: {n_ok}/{n_realizations} OK, "
        f"{n_err} errors → {out_path}"
    )
    return df


# ---------------------------------------------------------------------------
# CLI entry point
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--sample-id",
        type=int,
        required=True,
        help="Row index in sobol_samples.csv to run (= SLURM_ARRAY_TASK_ID).",
    )
    parser.add_argument(
        "--samples-csv",
        type=Path,
        required=True,
        help="Path to sobol_samples.csv (generated by sobol_design.py).",
    )
    parser.add_argument(
        "--syn-flows-dir",
        type=Path,
        default=_THIS_FILE.parents[1] / "results" / "sobol" / "synthetic_flows",
        help=(
            "Directory of Kirsch-Nowak synthetic flow parquet files "
            "(generated by gen_synthetic_flows.py).  "
            "Default: D4_distributed_risk/results/sobol/synthetic_flows/"
        ),
    )
    parser.add_argument(
        "--n-realizations",
        type=int,
        default=SOBOL_ENSEMBLE_SUBSET,
        help=f"Number of synthetic realizations per Sobol sample (default: {SOBOL_ENSEMBLE_SUBSET}).",
    )
    parser.add_argument(
        "--outdir",
        type=Path,
        default=_THIS_FILE.parents[1] / "results" / "sobol" / "task_outputs",
        help="Output directory for task CSVs (default: D4_distributed_risk/results/sobol/task_outputs/).",
    )
    parser.add_argument(
        "--n-workers",
        type=int,
        default=1,
        help=(
            "Number of parallel worker processes for realizations (default: 1). "
            "Set to SOBOL_ENSEMBLE_SUBSET (50) or SLURM_CPUS_PER_TASK for full parallelism."
        ),
    )
    parser.add_argument(
        "--log-level",
        default="INFO",
        choices=["DEBUG", "INFO", "WARNING", "ERROR"],
    )
    args = parser.parse_args()

    logging.basicConfig(
        level=getattr(logging, args.log_level),
        format="%(asctime)s %(levelname)-8s %(message)s",
        datefmt="%H:%M:%S",
    )
    _configure_worker_logging(logging.WARNING)

    logger.info(f"Sobol sweep task {args.sample_id}")

    # --- Load sample params ---
    samples_df = pd.read_csv(args.samples_csv, index_col=0)
    if args.sample_id >= len(samples_df):
        raise IndexError(
            f"sample_id={args.sample_id} out of range "
            f"(sobol_samples.csv has {len(samples_df)} rows)."
        )
    sample_row    = samples_df.iloc[args.sample_id]
    sample_params = sample_row.to_dict()
    logger.info(f"  Parameters: {sample_params}")

    # --- Verify synthetic flows directory exists ---
    if not args.syn_flows_dir.exists():
        raise FileNotFoundError(
            f"Synthetic flows directory not found: {args.syn_flows_dir}\n"
            "Run gen_synthetic_flows.py first:\n"
            "  python sensitivity/gen_synthetic_flows.py"
        )
    n_parquets = len(list(args.syn_flows_dir.glob("realization_*.parquet")))
    if n_parquets < args.n_realizations:
        raise FileNotFoundError(
            f"Found only {n_parquets} realization parquet files in {args.syn_flows_dir}, "
            f"expected {args.n_realizations}.  Re-run gen_synthetic_flows.py."
        )
    logger.info(f"  Synthetic flows dir: {args.syn_flows_dir} ({n_parquets} realizations)")

    # --- Run task ---
    run_one_sobol_task(
        sample_id=args.sample_id,
        sample_params=sample_params,
        syn_flows_dir=args.syn_flows_dir,
        n_realizations=args.n_realizations,
        outdir=args.outdir,
        n_workers=args.n_workers,
    )

    logger.info("Done.")


if __name__ == "__main__":
    main()
