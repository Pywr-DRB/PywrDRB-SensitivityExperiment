"""
Pre-generate predicted_inflows_mgd.csv for Amestoy ensemble members.

Run this ONCE before the Sobol sweep to populate the prediction cache.
The cache is read by run_model.run_single(predicted_inflows_cache=...) and
avoids regenerating predictions (~5 min each) inside every SLURM task.

Each member's flows are unique, so predictions must be computed per member.
With the cache, Sobol sweep tasks copy from cache (seconds) instead of
recomputing (minutes), reducing per-task overhead from ~250 min to ~150 min.

Usage
-----
    # Pre-generate for all 50 subset members (after subset_members.py):
    python sensitivity/preprocess_amestoy_members.py \\
        --subset-members results/sobol/subset_members.txt \\
        --amestoy-path ~/data/amestoy_2026 \\
        --n-workers 10

    # Or for all 1000 baseline members:
    python sensitivity/preprocess_amestoy_members.py \\
        --all-members \\
        --amestoy-path ~/data/amestoy_2026 \\
        --n-workers 20
"""

from __future__ import annotations

import argparse
import logging
import sys
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

# ---------------------------------------------------------------------------
# Path setup
# ---------------------------------------------------------------------------
_THIS_FILE = Path(__file__).resolve()
_REPO_ROOT = _THIS_FILE.parents[2]
_SHARED    = _REPO_ROOT / "shared"
for _p in [str(_SHARED), str(_REPO_ROOT)]:
    if _p not in sys.path:
        sys.path.insert(0, _p)

from pywrdrb_utils.amestoy_io import load_member_flows, INPUTS_HDF5_SUBPATH
from pywrdrb_utils.run_model import _generate_predicted_inflows, write_synthetic_inputs

logger = logging.getLogger(__name__)

INPUTS_HDF5_SUBPATH = (
    "pywrdrb_inputs/historic_ensembles"
    "/catchment_inflow_obs_pub_nhmv10_BC_ObsScaled_ensemble.hdf5"
)


def preprocess_one_member(
    member_id: int,
    inputs_hdf5: Path,
    cache_dir: Path,
) -> dict:
    """
    Generate predicted_inflows_mgd.csv for one Amestoy member and cache it.

    Parameters
    ----------
    member_id : int
        0-based ensemble member index.
    inputs_hdf5 : Path
        Amestoy inputs HDF5 path.
    cache_dir : Path
        Root cache directory.  Output: cache_dir/{inflow_type}/predicted_inflows_mgd.csv

    Returns
    -------
    dict with keys: member_id, status, cache_path
    """
    import pywrdrb
    import tempfile
    import shutil

    inflow_type = f"obs_pub_nhmv10_BC_ObsScaled_m{member_id:04d}"
    cache_path = cache_dir / inflow_type / "predicted_inflows_mgd.csv"

    if cache_path.exists():
        return {"member_id": member_id, "status": "cached", "cache_path": str(cache_path)}

    try:
        # Load flows and write to temp inputs dir
        flow_df = load_member_flows(inputs_hdf5, member_id)

        with tempfile.TemporaryDirectory(prefix=f"pywrdrb_preproc_{inflow_type}_") as tmpdir:
            inputs_dir = Path(tmpdir) / "inputs" / inflow_type
            write_synthetic_inputs(flow_df, inputs_dir)

            # Register path navigator
            pn_config = pywrdrb.get_pn_config()
            pn_config[f"flows/{inflow_type}"] = str(inputs_dir.resolve())
            pywrdrb.load_pn_config(pn_config)

            # Generate predictions
            _generate_predicted_inflows(inflow_type, inputs_dir)

            # Copy to cache
            cache_path.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(inputs_dir / "predicted_inflows_mgd.csv", cache_path)

        logger.info(f"  member {member_id:4d}: generated + cached → {cache_path}")
        return {"member_id": member_id, "status": "generated", "cache_path": str(cache_path)}

    except Exception as exc:
        logger.error(f"  member {member_id:4d}: FAILED — {exc}")
        return {"member_id": member_id, "status": f"error: {exc}", "cache_path": None}


def main():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--subset-members",
        type=Path,
        default=None,
        help=(
            "Path to subset_members.txt (generated by subset_members.py). "
            "Pre-generate predictions for these members only."
        ),
    )
    parser.add_argument(
        "--all-members",
        action="store_true",
        default=False,
        help="Pre-generate predictions for all 1000 Amestoy members.",
    )
    parser.add_argument(
        "--member-ids",
        nargs="+",
        type=int,
        default=None,
        help="Explicit list of member IDs to process.",
    )
    parser.add_argument(
        "--amestoy-path",
        type=Path,
        default=Path.home() / "data" / "amestoy_2026",
        help="Root directory of extracted Amestoy data (default: ~/data/amestoy_2026).",
    )
    parser.add_argument(
        "--n-workers",
        type=int,
        default=4,
        help="Number of parallel workers (default: 4).",
    )
    parser.add_argument(
        "--log-level",
        default="INFO",
        choices=["DEBUG", "INFO", "WARNING", "ERROR"],
    )
    args = parser.parse_args()

    logging.basicConfig(
        level=getattr(logging, args.log_level),
        format="%(asctime)s  %(levelname)-8s  %(message)s",
        datefmt="%H:%M:%S",
    )

    # Determine member list
    if args.all_members:
        member_ids = list(range(1000))
    elif args.subset_members is not None:
        if not args.subset_members.exists():
            raise FileNotFoundError(
                f"subset_members.txt not found: {args.subset_members}\n"
                "Run subset_members.py first."
            )
        member_ids = [int(x) for x in args.subset_members.read_text().split() if x.strip()]
    elif args.member_ids is not None:
        member_ids = args.member_ids
    else:
        raise ValueError(
            "Specify --subset-members, --all-members, or --member-ids."
        )

    inputs_hdf5 = args.amestoy_path / INPUTS_HDF5_SUBPATH
    if not inputs_hdf5.exists():
        raise FileNotFoundError(f"Inputs HDF5 not found: {inputs_hdf5}")

    cache_dir = inputs_hdf5.parent / "predicted_inflows_cache"
    cache_dir.mkdir(parents=True, exist_ok=True)

    logger.info(f"Pre-generating predicted_inflows_mgd.csv for {len(member_ids)} members")
    logger.info(f"  inputs_hdf5: {inputs_hdf5}")
    logger.info(f"  cache_dir:   {cache_dir}")
    logger.info(f"  n_workers:   {args.n_workers}")
    logger.info(f"  ETA:         ~{len(member_ids) * 5 / args.n_workers:.0f} min")

    n_ok = n_cached = n_err = 0
    if args.n_workers <= 1:
        for mid in member_ids:
            r = preprocess_one_member(mid, inputs_hdf5, cache_dir)
            if r["status"] == "generated": n_ok += 1
            elif r["status"] == "cached": n_cached += 1
            else: n_err += 1
    else:
        with ProcessPoolExecutor(max_workers=args.n_workers) as pool:
            futures = {
                pool.submit(preprocess_one_member, mid, inputs_hdf5, cache_dir): mid
                for mid in member_ids
            }
            done = 0
            for fut in as_completed(futures):
                r = fut.result()
                done += 1
                if r["status"] == "generated": n_ok += 1
                elif r["status"] == "cached": n_cached += 1
                else: n_err += 1
                if done % 10 == 0:
                    logger.info(f"  Progress: {done}/{len(member_ids)} "
                                f"({n_ok} generated, {n_cached} cached, {n_err} errors)")

    logger.info(f"Done: {n_ok} generated, {n_cached} already cached, {n_err} errors")
    logger.info(f"Cache: {cache_dir}")


if __name__ == "__main__":
    main()
